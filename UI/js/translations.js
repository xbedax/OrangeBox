var selectedLanguage = "en";

function tr(key) {
    return translations[selectedLanguage]?.[key]
        ?? translations.en?.[key]
        ?? `[${key}]`;
}

function translatePage() {
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.dataset.i18n;
		console.log ("Processing :" + key); 
        el.textContent = translations[selectedLanguage][key] ?? translations.en?.[key] ?? `[${key}]`;
    });
    document.querySelectorAll("[data-i18n-title]").forEach(el => {
        el.title = tr(el.dataset.i18nTitle);
    });
    document.querySelectorAll("[data-i18n-tooltip]").forEach(el => {
        el.dataset.tooltip = tr(el.dataset.i18nTooltip);
    });
	document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
		el.placeholder = tr(el.dataset.i18nPlaceholder);
    });

    document.documentElement.lang = selectedLanguage;
}

function getLanguage() {
    const lang = navigator.languages?.[0] || navigator.language || "en";
    const short = lang.split("-")[0].toLowerCase();

    return translations[short] ? short : "en";
}